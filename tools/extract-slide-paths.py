#!/usr/bin/env python3
"""Extract ordered slide-arrow positions from a MajdataPlay checkout.

Run from the MaiPlay repository:
    python tools/extract-slide-paths.py .reference/MajdataPlay

The generated data is derived from MajdataPlay's GPL-3.0 prefabs. Only the
root Transform's ordered children are used; its final SlideOK child is omitted.
"""

import argparse
from pathlib import Path
import re
import subprocess


SOURCE_COMMIT = "dc19722d602f099131d93b37091624ad30150ad1"
SOURCE_DIRECTORY = Path("Assets/Prefabs/Game/Slides")
SOURCE_URL = "https://github.com/TeamMajdata/MajdataPlay"


def records(text, kind):
    pattern = rf"^--- !u!{kind} &(-?\d+)\n(.*?)(?=^---|\Z)"
    return {match[1]: match[2] for match in re.finditer(pattern, text, re.M | re.S)}


def extract(prefab):
    text = prefab.read_text(encoding="utf-8")
    transforms = records(text, 4)
    roots = [value for value in transforms.values() if "m_Father: {fileID: 0}" in value]
    if len(roots) != 1:
        raise ValueError(f"{prefab.name}: expected one root Transform")
    root = roots[0]
    for field, expected in (
        ("m_LocalPosition", "{x: 0, y: 0, z: 0}"),
        ("m_LocalRotation", "{x: 0, y: 0, z: 0, w: 1}"),
        ("m_LocalScale", "{x: 1, y: 1, z: 1}"),
    ):
        if re.search(rf"  {field}: (.*)", root)[1] != expected:
            raise ValueError(f"{prefab.name}: nonidentity root {field}")
    children = root.split("m_Children:", 1)[1].split("m_Father:", 1)[0]
    child_ids = re.findall(r"fileID: (-?\d+)", children)
    points = []
    for child_id in child_ids[:-1]:
        position = re.search(r"m_LocalPosition: \{x: ([^,]+), y: ([^,]+), z: ([^}]+)\}", transforms[child_id])
        x, y, z = map(float, position.groups())
        if z != 0:
            raise ValueError(f"{prefab.name}: arrow outside the slide plane")
        points.append((x / 4.8, -y / 4.8))
    name = re.search(r"_slideType: (\w+)", text)[1]
    return name, points


def generate(source):
    revision = subprocess.check_output(
        ["git", "-C", str(source), "rev-parse", "HEAD"], text=True
    ).strip()
    if revision != SOURCE_COMMIT:
        raise ValueError(f"Expected MajdataPlay {SOURCE_COMMIT}, found {revision}")
    lines = [
        "// <auto-generated>",
        "// Ordered slide-arrow positions derived from MajdataPlay (GPL-3.0).",
        f"// Source: {SOURCE_URL}",
        f"// Revision: {SOURCE_COMMIT}",
        f"// Prefabs: {SOURCE_DIRECTORY.as_posix()}/Star_*.prefab",
        "// Regenerate: python tools/extract-slide-paths.py .reference/MajdataPlay",
        "// Coordinates: (Unity x / 4.8, -Unity y / 4.8); excludes endpoints and SlideOK.",
        "// </auto-generated>",
        "namespace MaiPlay.Core;",
        "",
        "internal static class SlidePathSamples",
        "{",
        "    internal static IReadOnlyList<ChartPoint> Get(string name) => Samples[name];",
        "",
        "    private static readonly Dictionary<string, ChartPoint[]> Samples = new()",
        "    {",
    ]
    count = 0
    prefabs = sorted((source / SOURCE_DIRECTORY).glob("Star_*.prefab"))
    if not prefabs:
        raise ValueError(f"No slide prefabs found under {source / SOURCE_DIRECTORY}")
    for prefab in prefabs:
        name, points = extract(prefab)
        count += len(points)
        lines.extend([f"        // {prefab.name}", f'        ["{name}"] =', "        ["])
        for start in range(0, len(points), 3):
            values = ", ".join(f"new({x:.12g}, {y:.12g})" for x, y in points[start:start + 3])
            lines.append(f"            {values},")
        lines.append("        ],")
    lines.extend(["    };", "}", ""])
    return "\n".join(lines), len(prefabs), count


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="MajdataPlay checkout at the pinned revision")
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "src/MaiPlay.Core/SlidePathSamples.cs")
    args = parser.parse_args()
    content, prefab_count, point_count = generate(args.source)
    args.output.write_text(content, encoding="utf-8", newline="\n")
    print(f"Extracted {point_count} arrow positions from {prefab_count} prefabs to {args.output}")


if __name__ == "__main__":
    main()
