"""Extract fixed MajdataPlay TouchSensorMapper polygons; keep C1/C2 under logical C."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
source = root / '.reference/MajdataPlay/Assets/Scripts/IO/PdxTouch/TouchSensorMapper.cs'
text = source.read_text(encoding='utf-8-sig')
polygons = re.findall(r'MakePolygon\((\d+),\s*(\d+),\s*new Vector2\[\]\s*\{(.*?)\}\)', text, re.S)
assert len(polygons) == 34
areas = [f'{g}{i}' for g in 'AB' for i in range(1, 9)] + ['C', 'C'] + [f'{g}{i}' for g in 'DE' for i in range(1, 9)]
lines = [
    '// Polygon data copied from TeamMajdata/MajdataPlay, GPL-3.0.',
    '// dc19722d602f099131d93b37091624ad30150ad1, IO/PdxTouch/TouchSensorMapper.cs.',
    '// Generated by tools/extract-sensor-polygons.py. Coordinates retain the 1440-pixel source canvas.',
    'namespace MaiPlay.Core;', '', 'public sealed record SensorPolygon(SensorArea Area, IReadOnlyList<ChartPoint> Points);', '',
    'public static partial class ContactMapper', '{', '    public static IReadOnlyList<SensorPolygon> SensorPolygons { get; } =', '    ['
]
for area, (x, y, points) in zip(areas, polygons):
    coords = re.findall(r'new Vector2\((\d+),\s*(\d+)\)', points)
    joined = ', '.join(f'P({int(x)+int(px)}, {int(y)+int(py)})' for px, py in coords)
    lines.append(f'        new(SensorArea.{area}, [{joined}]),')
lines += ['    ];', '', '    private static ChartPoint P(int x, int y) => new((x - 720d) / 720, (y - 720d) / 720);', '}']
(root / 'src/MaiPlay.Core/SensorPolygons.cs').write_text('\n'.join(lines) + '\n', encoding='utf-8')
