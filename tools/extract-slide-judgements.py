"""Extract standard modern slide sensor tables from the pinned MajdataPlay source."""
from pathlib import Path
import re
import sys

revision = "dc19722d602f099131d93b37091624ad30150ad1"
source = Path(sys.argv[1]) / "Assets/Scripts/Scenes/Game/Utils/SlideTables.cs"
text = source.read_text(encoding="utf-8-sig")


def areas(body):
    result = []
    for call in re.findall(r"BuildSlideArea\((.*?)\)", body, re.S):
        sensors = re.findall(r"SensorArea\.\w+", call)
        tail = call[call.rfind("}") + 1:] if "}" in call else call[call.index(","):]
        args = [arg.strip() for arg in tail.split(",") if arg.strip()]
        on = args.pop(0)
        off = args.pop(0) if args and args[0] not in ("true", "false") else on
        skip = args.pop(0) if args else "true"
        last = args.pop(0) if args else "false"
        result.append(f"new([{', '.join(sensors)}], {on}, {off}, {skip}, {last})")
    return result


tables = re.findall(r'Name = "([^"]+)"\s*,\s*JudgeQueue = new PredefinedSlideArea\[\]\s*\{(.*?)\},\s*Const = ([\d.]+)f', text, re.S)
wifi = text.split("WIFISLIDE_JUDGE_QUEUE =", 1)[1].split("WIFISLIDE_JUDGE_QUEUE_CLASSIC", 1)[0]
wifi_queues = dict(re.findall(r"(Left|Center|Right) = new PredefinedSlideArea\[\].*?\{(.*?)^\s*\},", wifi, re.S | re.M))
wifi_constant = re.search(r"Const = ([\d.]+)f", wifi)[1]

lines = [
    "// <auto-generated>",
    "// Adapted from MajdataPlay by TeamMajdata and contributors, licensed under GPL-3.0.",
    f"// Revision: {revision}",
    "// Source: Assets/Scripts/Scenes/Game/Utils/SlideTables.cs",
    "// Original license: licenses/MajdataPlay-GPL-3.0.txt",
    "// Regenerate: python tools/extract-slide-judgements.py .reference/MajdataPlay",
    "// Modern rules only; Unity pools and rendering objects are omitted.",
    "// </auto-generated>",
    "namespace MaiPlay.Core;",
    "",
    "internal sealed record SlideAreaDefinition(SensorArea[] Areas, int ProgressOn, int ProgressOff, bool Skippable, bool Last);",
    "internal sealed record SlideTableDefinition(double TailConstant, SlideAreaDefinition[][] Queues);",
    "",
    "internal static class SlideJudgeTables",
    "{",
    "    internal static SlideTableDefinition Get(string name) => Tables[name];",
    "",
    "    private static readonly Dictionary<string, SlideTableDefinition> Tables = new()",
    "    {",
]
for name, body, constant in tables:
    lines.extend([f'        ["{name}"] = new({constant}, [[', *[f"            {a}," for a in areas(body)], "        ]]),"])
lines.extend([f'        ["wifi"] = new({wifi_constant}, [', "            // Branch order matches SlidePath: centre, end - 1, end + 1."])
for branch in ("Center", "Right", "Left"):
    lines.extend(["            [", *[f"                {a}," for a in areas(wifi_queues[branch])], "            ],"])
lines.extend(["        ]),", "    };", "}", ""])
destination = Path(__file__).resolve().parents[1] / "src/MaiPlay.Core/SlideJudgeTables.cs"
destination.write_text("\n".join(lines), encoding="utf-8")
print(f"Extracted {len(tables)} standard tables and 3 modern Wifi queues to {destination}")
